<?php
require '/var/www/html/wp-load.php';
$checks=[];
$assert=function($k,$test)use(&$checks){$checks[$k]=(bool)$test;};
$fixture=['rate_id'=>66526,'checkin'=>'2026-12-01','checkout'=>'2026-12-03','rooms'=>1,'adults'=>2,'children'=>1];
$before=\BookingExperience\unified_accommodation_preview($fixture);
$assert('legacy_pricing_unchanged',!is_wp_error($before)&&abs($before['preview_total']-240)<.001);
$unconfigured=\BookingExperience\unified_accommodation_preview($fixture+['child_ages'=>[1]]);
$assert('no_silent_age_policy',is_wp_error($unconfigured)&&$unconfigured->get_error_code()==='stay_age_policy_unconfigured');
$bands=[['id'=>'infant','min_age'=>0,'max_age'=>2,'price_factor'=>0.0,'count_in_capacity'=>false],['id'=>'child','min_age'=>3,'max_age'=>17,'price_factor'=>0.5,'count_in_capacity'=>true]];
$apply=function($record,$level,$context)use($bands){return $level==='rate' && (int)($context['rate_id']??0)===66526?['bands'=>$bands,'age_pricing_enabled'=>true]:$record;};
add_filter('mad4b/age_occupancy/policy_level',$apply,20,3);
$infant=\BookingExperience\unified_accommodation_preview($fixture+['child_ages'=>[1]]);
$assert('infant_age_accepted',!is_wp_error($infant)&&abs($infant['preview_total']-240)<.001);
$receipt=is_wp_error($infant)?[]:($infant['provider_source_quote']['age_policy_receipt']??[]);
$assert('infant_capacity_exempt',($receipt['capacity_children'][0]??null)===0&&($receipt['child_price_units']??null)===0.0);
$child=\BookingExperience\unified_accommodation_preview($fixture+['child_ages'=>[7]]);
$receipt=is_wp_error($child)?[]:($child['provider_source_quote']['age_policy_receipt']??[]);
$assert('child_age_banded',!is_wp_error($child)&&($receipt['capacity_children'][0]??null)===1&&abs($receipt['child_price_units']-.5)<.001);
$assert('room_basis_stable',!is_wp_error($child)&&abs($child['preview_total']-240)<.001);
$incorrect=\BookingExperience\unified_accommodation_preview($fixture+['child_ages'=>[1,7]]);
$assert('age_count_reject',is_wp_error($incorrect)&&$incorrect->get_error_code()==='stay_age_count_mismatch');
$missing=\BookingExperience\unified_accommodation_preview($fixture+['child_ages'=>[19]]);
$assert('unmapped_age_reject',is_wp_error($missing)&&$missing->get_error_code()==='stay_age_band_missing');
$room_child=\BookingExperience\unified_accommodation_preview($fixture+['room_occupancy'=>[['adults'=>2,'children'=>1,'child_ages'=>[7]]]]);
$assert('room_assignment_ages',!is_wp_error($room_child)&&abs($room_child['preview_total']-$child['preview_total'])<.001);
$other=MAD4B_Age_Aware_Stay::preview(['child_ages'=>[7]],0,0,99999,2,1,1);
$assert('unconfigured_rate_reject',is_wp_error($other)&&$other->get_error_code()==='stay_age_policy_unconfigured');
$direct=MAD4B_Pricing_Quote_Dispatch::preview('accommodation_rate',$fixture+['child_ages'=>[7]]);
$assert('registry_dispatch_parity',!is_wp_error($direct)&&$direct['quote']['preview_total']===$child['preview_total']);
$multi=$fixture;
$multi['rooms']=2;$multi['adults']=4;$multi['children']=2;
$multi['room_occupancy']=[['adults'=>2,'children'=>1,'child_ages'=>[1]],['adults'=>2,'children'=>1,'child_ages'=>[1]]];
$mq=\BookingExperience\unified_accommodation_preview($multi);
$assert('multiroom_age_capacity',!is_wp_error($mq)&&($mq['provider_source_quote']['age_policy_receipt']['capacity_children']??[])===[0,0]);
$assert('multiroom_room_pricing_stable',!is_wp_error($mq)&&abs($mq['preview_total']-480)<.001);
$polGlobal=function($r,$level,$ctx){if($level==='global')return ['age_reference'=>'checkin'];return $r;};
add_filter('mad4b/age_occupancy/policy_level',$polGlobal,15,3);
$p=MAD4B_Age_Occupancy_Registry::policy(['domain'=>'accommodation','rate_id'=>66526]);
$assert('policy_overrides_traced',!is_wp_error($p)&&in_array('global',$p['overrides'],true)&&in_array('rate',$p['overrides'],true));
remove_filter('mad4b/age_occupancy/policy_level',$polGlobal,15);
$child_units=(2+$receipt['child_price_units']);
$assert('per_person_factor_fixture',abs($child_units-2.5)<.001&&abs(MAD4B_Age_Aware_Stay::multiplier('per_person',2,1,2,1,$receipt)-2.5)<.001);
$assert('per_person_night_age_pricing',abs(MAD4B_Age_Aware_Stay::multiplier('per_person_night',2,1,2,1,$receipt)-5.0)<.001);
$assert('room_night_unchanged',MAD4B_Age_Aware_Stay::multiplier('per_room_night',2,1,2,1,$receipt)===2);
remove_filter('mad4b/age_occupancy/policy_level',$apply,20);
foreach($checks as $name=>$ok)echo $name.'='.($ok?'PASS':'FAIL').PHP_EOL;
echo 'SUMMARY='.count(array_filter($checks)).'/'.count($checks).PHP_EOL;
exit(in_array(false,$checks,true)?1:0);
