/* Explicit, serialized administrator reports. A client abort cannot cancel PHP. */
(() => {
  'use strict';
  document.querySelectorAll('[data-mad4b-reports]').forEach(root => {
    let busy = false;
    const buttons = [...root.querySelectorAll('[data-report]')];
    buttons.forEach(button => button.addEventListener('click', async () => {
      if (busy) return;
      busy = true;
      buttons.forEach(b => { b.disabled = true; });
      const key = button.dataset.report;
      const result = root.querySelector(`[data-report-result="${key}"]`);
      const content = root.querySelector(`[data-report-content="${key}"]`);
      result.textContent = 'Checking…';
      content.replaceChildren();
      const controller = new AbortController();
      let timedOut = false;
      const timer = setTimeout(() => { timedOut = true; controller.abort(); }, 12000);
      let stopped = false;
      try {
        const response = await fetch(root.dataset.url, {
          method: 'POST', credentials: 'same-origin', signal: controller.signal,
          body: new URLSearchParams({action: 'mad4b_admin_report', nonce: root.dataset.nonce, report: key})
        });
        if (!response.ok) throw new Error(`HTTP ${response.status}`);
        const payload = await response.json();
        if (timedOut) throw new Error('Timeout');
        if (!payload.success || !payload.data || typeof payload.data.elapsed_ms !== 'number' || typeof payload.data.query_count !== 'number') throw new Error('Invalid report');
        const data = payload.data;
        const state = ['MEASURED', 'REPORT_FAILED', 'BUDGET_EXCEEDED'].includes(data.state) ? data.state : 'NOT_CHECKED';
        result.textContent = `${state} · ${data.elapsed_ms} ms · ${data.query_count} queries · readiness: ${data.ready === true ? 'observed locally' : data.ready === false ? 'not ready' : 'not verified'}`;
        // HTML is generated by the existing administrator renderer, never provider fields.
        if (['chatgpt', 'workspace'].includes(key) && typeof data.html === 'string' && data.html) {
          const parsed = new DOMParser().parseFromString(data.html, 'text/html');
          parsed.querySelectorAll('script').forEach(node => node.remove());
          content.replaceChildren(...parsed.body.childNodes);
        }
        stopped = state !== 'MEASURED';
      } catch (error) {
        result.textContent = timedOut ? 'Timeout — Not checked. Reload before retrying; PHP may still be running.' : 'Request failed — Not checked. Reload before retrying.';
        stopped = true;
      } finally {
        clearTimeout(timer);
        if (!stopped) { busy = false; buttons.forEach(b => { b.disabled = false; }); }
      }
    }));
  });
})();
