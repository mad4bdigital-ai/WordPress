<?php
/**
 * Plugin Name: MAD4B Staging LiteSpeed Selective Static Inline CSS
 * Description: Combine static external and inline CSS without embedding per-request Elementor/JetEngine dynamic selector rules.
 * Version: 1.0.1
 */
defined('ABSPATH') || exit;

final class MAD4B_LiteSpeed_Selective_Inline_CSS_V1 {
 private const HOST='tours.dev.mad4b.com';
 private const SITE_UUID='e5e64bca-ed62-48d2-b2b3-dff693cd702a';
 private const EXPECT_LS='7.9.2';
 private const EXPECT_EL='4.3.5';
 private const PATHS=[
  '/tours-and-activities/'=>'en', '/fr/tours-and-activities/'=>'fr',
  '/ar/tours-and-activities/'=>'ar','/de/tours-and-activities/'=>'de',
  '/es/tours-and-activities/'=>'es','/it/tours-and-activities/'=>'it',
 ];
 private const TRACKING_COOKIES=[
  'sbjs_current'=>1,'sbjs_current_add'=>1,'sbjs_first'=>1,'sbjs_first_add'=>1,
  'sbjs_migrations'=>1,'sbjs_session'=>1,'sbjs_udata'=>1,
  '_ga'=>1,'_gid'=>1,'_gcl_au'=>1,
 ];
 public static function safe_cookies(array $cookies,string $locale): bool {
  foreach($cookies as $key=>$value){
   if(!is_string($key)||!is_string($value))return false;
   if($key==='wp-wpml_current_language'){
    if(!hash_equals($locale,rawurldecode($value)))return false;
    continue;
   }
   if(isset(self::TRACKING_COOKIES[$key]))continue;
   if(preg_match('/^_ga_[A-Za-z0-9]{4,24}$/D',$key))continue;
   return false; // Unknown/price/cart/auth/geo/session cookies retain native behavior.
  }
  return true;
 }

 public static function safe_raw_cookie_header(string $header,string $locale): bool {
  // WPML may mutate the PHP $_COOKIE language entry while resolving the route.
  // Validate the original user-supplied header instead.
  if(strlen($header)>4096)return false;
  $cookies=[];
  foreach(explode(';',$header) as $part){
   $part=trim($part);
   if($part==='')continue;
   $pos=strpos($part,'=');
   if($pos===false)return false;
   $name=trim(substr($part,0,$pos));
   if($name==='' || !preg_match('/^[A-Za-z0-9_-]{1,80}$/D',$name)
      ||array_key_exists($name,$cookies))return false;
   $cookies[$name]=substr($part,$pos+1);
  }
  return self::safe_cookies($cookies,$locale);
 }
 private static function eligible(): bool {
  if(PHP_SAPI==='cli'||wp_get_environment_type()!=='staging'
   ||is_admin()||wp_doing_ajax()||is_user_logged_in()||is_preview()
   ||($_SERVER['REQUEST_METHOD']??'')!=='GET'
   ||($_SERVER['HTTP_HOST']??'')!==self::HOST
   ||(string)wp_parse_url(home_url(),PHP_URL_HOST)!==self::HOST
   ||!empty($_SERVER['QUERY_STRING'])||!empty($_SERVER['HTTP_AUTHORIZATION'])
   ||!empty($_SERVER['HTTP_X_MAD4B_CURRENCY'])
   ||!empty($_SERVER['HTTP_X_GEO_COUNTRY'])
   ||!empty($_SERVER['HTTP_CF_IPCOUNTRY'])
   ||!empty($_SERVER['HTTP_X_FORWARDED_GEO_COUNTRY'])
   ||($_SERVER['HTTP_X_MAD4B_CSS_SELECTIVE_CONTROL']??'')==='native-v1'
   ||($_SERVER['HTTP_X_MAD4B_CSS_COMBINE_CANARY']??'')!=='')return false;
  $path=(string)wp_parse_url($_SERVER['REQUEST_URI']??'',PHP_URL_PATH);
  $locale=self::PATHS[$path]??null;
  if($locale===null||apply_filters('wpml_current_language',null)!==$locale
   ||!self::safe_raw_cookie_header((string)($_SERVER['HTTP_COOKIE']??''),$locale)
   ||!function_exists('get_woocommerce_currency')
   ||get_woocommerce_currency()!=='USD')return false;
  $profile=get_option('mad4b_scp_brand_context_profile_v1',[]);
  if(!is_array($profile)||($profile['site_uuid']??'')!==self::SITE_UUID)return false;
  if(!defined('LSCWP_V')||LSCWP_V!==self::EXPECT_LS
   ||!defined('ELEMENTOR_VERSION')||ELEMENTOR_VERSION!==self::EXPECT_EL)return false;
  // Original LiteSpeed configuration must remain stable; no global changes.
  if((string)get_option('litespeed.conf.optm-css_comb')!=='1'
   ||(string)get_option('litespeed.conf.optm-css_comb_ext_inl')!=='0')return false;
  return true;
 }
 public static function activate(): void {
  if(!self::eligible())return;
  // Official LiteSpeed 7.9.2 runtime configuration hooks. No option mutation.
  add_filter('litespeed_conf_load_option_optm-css_comb',static fn($value)=>'1',9999);
  add_filter('litespeed_conf_load_option_optm-css_comb_ext_inl',static fn($value)=>'1',9999);
  // CSS generated by Elementor per rendered JetEngine card includes a fresh
  // elementor-dcss-<unique> selector. Folding this into LiteSpeed's hashed
  // file creates a new 3MB CSS URL on every request, destroying browser reuse.
  add_filter('litespeed_optimize_css_excludes',static function($excludes){
   if(!is_array($excludes))return $excludes;
   $excludes[]='elementor-dcss-';
   return $excludes;
  },9999);
 }
}
add_action('wp',['MAD4B_LiteSpeed_Selective_Inline_CSS_V1','activate'],105);
