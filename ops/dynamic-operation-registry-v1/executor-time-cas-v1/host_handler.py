OPERATION="company.resource.cas.apply"
CONTRACT="mad4b.company-resource.executor-cas-plan.v1"
ROOT=Path("/opt/mad4b-company-transport/native-313-independent")
DYNAMIC=ROOT/"dynamic-operation-registry-v1/enrolled"
PLANS=Path("/var/lib/mad4b/dynamic-operation-registry/plans")
RESERVED=ROOT/"reserved"
RECEIPTS=ROOT/"receipts"
WORDPRESS_HOST_PROOF=Path("/opt/mad4b-company-transport/broker-v1/company-native-host-proof.py")
BROKER_KEY=Path("/opt/mad4b-company-transport/broker-v1/host-ed25519-public.base64")
# Exact root-protected signed release approval; not an owner certificate/OAuth
# request and never auto-generated by this handler.
CAS_GRANTS=Path("/var/lib/mad4b/company-resource-cas/grants")
GRANT_CONTRACT="mad4b.company-resource-cas.authorization.v1"
GRANT_FIELDS=[
    "contract","issuer","action","original_job_id","operation_id",
    "company","environment","site_uuid","origin","grant_id","transport_id",
    "plan_sha256","source_plan_sha256","command_sha256","resource_key",
    "meta_key","expected_before_sha256","expected_after_sha256",
    "expected_company_preservation_sha256","issued_epoch","expires_epoch","nonce",
]
FIELDS=[
 "contract","original_job_id","company_code","environment",
 "site_uuid","canonical_origin","native_operation",
 "source_plan_sha256","resource_type","resource_id","post_type",
 "meta_key","meta_id","expected_before_sha256",
 "expected_manifest_sha256","expected_company_preservation_sha256",
 "expected_meta_value_sha256","new_meta_value_sha256",
 "expected_after_sha256","issued_epoch","expires_epoch","nonce",
]
HEX32=re.compile(r"^[a-f0-9]{32}$")
HEX64=re.compile(r"^[a-f0-9]{64}$")


class CASRejected(ValueError):
    pass


def require(condition,reason):
    if not condition:
        raise CASRejected(reason)


def module_from_root(path:Path,name:str):
    st=path.lstat()
    require(st.st_uid==0 and stat.S_ISREG(st.st_mode) and
            not st.st_mode&0o022 and not path.is_symlink(),
            "ORIGINAL_EXECUTOR_SOURCE_NOT_TRUSTED")
    spec=importlib.util.spec_from_file_location(name,path)
    require(spec is not None and spec.loader is not None,
            "ORIGINAL_EXECUTOR_MODULE_UNAVAILABLE")
    module=importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def pinned_plan(job:str,plan_sha:str):
    require(HEX32.fullmatch(job) is not None and
            HEX64.fullmatch(plan_sha) is not None,
            "EXACT_ORIGINAL_JOB_AND_PLAN_REQUIRED")
    sys.path.insert(0,str(DYNAMIC))
    import registry
    import admission
    index=registry.Registry(DYNAMIC)
    manifest=index.resolve(OPERATION)
    plan=admission.checked_plan(PLANS,plan_sha,manifest)
    expected=index.command_sha256(OPERATION,plan_sha)
    require(plan.get("contract")==CONTRACT and
            manifest.get("plan_contract")==CONTRACT and
            plan.get("plan_sha256")==plan_sha,
            "DYNAMIC_CAS_PLAN_CONTRACT_MISMATCH")
    required={
        "contract","plan_sha256","company","environment","site_uuid","origin",
        "source_plan_sha256","resource_type","resource_id","post_type",
        "meta_key","meta_id","expected_before_sha256",
        "expected_manifest_sha256","expected_company_preservation_sha256",
        "expected_meta_value_sha256","new_meta_value_sha256",
        "expected_after_sha256","new_meta_value","old_meta_value"
    }
    require(set(plan)==required, "DYNAMIC_CAS_PLAN_FIELD_SET_INVALID")
    require(plan["resource_type"]=="wordpress.post" and
            isinstance(plan["resource_id"],str) and
            re.fullmatch(r"[1-9][0-9]{0,9}",plan["resource_id"]) and
            type(plan["meta_id"]) is int and plan["meta_id"]>0,
            "DYNAMIC_CAS_EXACT_RESOURCE_INVALID")
    for name in ["source_plan_sha256","expected_before_sha256",
                 "expected_manifest_sha256","expected_company_preservation_sha256",
                 "expected_meta_value_sha256","new_meta_value_sha256",
                 "expected_after_sha256"]:
        require(isinstance(plan[name],str) and
                HEX64.fullmatch(plan[name]) is not None,
                "DYNAMIC_CAS_DIGEST_INVALID")
    new=plan["new_meta_value"]
    old=plan["old_meta_value"]
    require(isinstance(new,str) and 0<len(new.encode())<=4096
            and hashlib.sha256(new.encode()).hexdigest()==plan["new_meta_value_sha256"],
            "SIGNED_PLAN_NEW_META_VALUE_DIGEST_MISMATCH")
    require(isinstance(old,str) and len(old.encode())<=4096
            and hashlib.sha256(old.encode()).hexdigest()==
                plan["expected_meta_value_sha256"],
            "EXACT_RESTORABLE_BEFORE_META_VALUE_NOT_PINNED")
    provider_scope=manifest.get("cas_scope")
    require(isinstance(provider_scope,dict)
            and set(provider_scope)=={
                "resource_type","allowed_post_types","allowed_meta_keys",
                "ownership_scope","commercial_pricing_allowed"}
            and provider_scope["resource_type"]=="wordpress.post"
            and provider_scope["ownership_scope"]=="tenant_owned"
            and provider_scope["commercial_pricing_allowed"] is False
            and isinstance(provider_scope["allowed_post_types"],list)
            and isinstance(provider_scope["allowed_meta_keys"],list)
            and len(provider_scope["allowed_post_types"])<=16
            and len(provider_scope["allowed_meta_keys"])<=32
            and plan["post_type"] in provider_scope["allowed_post_types"]
            and plan["meta_key"] in provider_scope["allowed_meta_keys"],
            "FIRST_PARTY_PROVIDER_MUTATION_SCOPE_NOT_ADMITTED")
    require(plan["expected_before_sha256"]!=plan["expected_after_sha256"],
            "CAS_BEFORE_AFTER_DIGEST_EQUAL")
    authority=admission.fresh_original_312(job,expected)
    now=int(time.time())
    require(isinstance(authority,dict)
            and authority.get("verified") is True
            and authority.get("eligible") is True
            and authority.get("owner_enrolled_wpcli") is True
            and authority.get("job_id")==job
            and authority.get("operation")=="company.remote.wpcli.full"
            and authority.get("command_sha256")==expected
            and authority.get("target_id")=="srv2030908"
            and all(authority.get(k)==plan[v]
                    for k,v in (("company","company"),
                                ("environment","environment"),
                                ("site_uuid","site_uuid"),
                                ("origin","origin")))
            and type(authority.get("expires_epoch")) is int
            and authority["expires_epoch"]>now+100,
            "EXACT_ORIGINAL_305_306_312_AUTHORITY_REQUIRED")
    # The dynamic Worker already reserved the exact job before entering
    # this handler. A manually invoked handler cannot create that reservation.
    path=RESERVED/(job+".reserved")
    st=path.lstat()
    require(stat.S_ISREG(st.st_mode) and st.st_uid==0 and
            not st.st_mode&0o077 and not path.is_symlink()
            and path.read_bytes()==
             ("dynamic:"+OPERATION+" "+expected+"\n").encode(),
            "EXACT_ORIGINAL_WORKER_RESERVATION_NOT_VERIFIED")
    return index,plan,authority,expected


def verify_signed_specific_grant(
    job:str,plan:dict,authority:dict,command_sha:str,*,now:int|None=None
)->dict:
    """Operation-specific, issuer-signed approval. Never issue or renew it.

    This is checked AFTER Original 312 and BEFORE any target WPCLI command.
    It grants no rights to generic meta/price changes outside the pinned
    first-party provider manifest and exact plan.
    """
    import registry
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey
    instant=int(time.time()) if now is None else now
    require(isinstance(job,str) and HEX32.fullmatch(job) is not None,
            "EXACT_ORIGINAL_JOB_ID_REQUIRED")
    root=CAS_GRANTS
    require(root.is_dir() and not root.is_symlink() and
            root.stat().st_uid==0 and not root.stat().st_mode&0o077,
            "SIGNED_CAS_GRANT_STORE_NOT_ENROLLED")
    path=root/(job+".json")
    raw=registry.protected_file(path,root,maximum=8192)
    grant=json.loads(raw)
    require(isinstance(grant,dict) and
            set(grant)==set(GRANT_FIELDS)|{"signature"} and
            grant.get("contract")==GRANT_CONTRACT and
            grant.get("issuer")=="mad4b-company-broker" and
            grant.get("action")=="apply" and
            grant.get("original_job_id")==job and
            grant.get("operation_id")==OPERATION and
            grant.get("company")==plan["company"] and
            grant.get("environment")==plan["environment"] and
            grant.get("site_uuid")==plan["site_uuid"] and
            grant.get("origin")==plan["origin"] and
            grant.get("plan_sha256")==plan["plan_sha256"] and
            grant.get("source_plan_sha256")==plan["source_plan_sha256"] and
            grant.get("command_sha256")==command_sha and
            grant.get("resource_key")==
                plan["resource_type"]+":"+plan["resource_id"] and
            grant.get("meta_key")==plan["meta_key"] and
            grant.get("expected_before_sha256")==plan["expected_before_sha256"] and
            grant.get("expected_after_sha256")==plan["expected_after_sha256"] and
            grant.get("expected_company_preservation_sha256")==
                plan["expected_company_preservation_sha256"] and
            grant.get("grant_id")==authority.get("grant_id") and
            grant.get("transport_id")==authority.get("transport_id") and
            type(grant.get("issued_epoch")) is int and
            type(grant.get("expires_epoch")) is int and
            instant-300<=grant["issued_epoch"]<=instant+10 and
            instant+60<grant["expires_epoch"]<=grant["issued_epoch"]+300 and
            isinstance(grant.get("nonce"),str) and
            HEX32.fullmatch(grant["nonce"]) is not None,
            "SIGNED_CAS_EXACT_OPERATION_RELEASE_SCOPE_OR_AGE_INVALID")
    pub=base64.b64decode(
        registry.protected_file(BROKER_KEY,BROKER_KEY.parent,maximum=128).strip(),
        validate=True)
    signature=base64.b64decode(grant["signature"],validate=True)
    require(len(pub)==32 and len(signature)==64,
            "SIGNED_CAS_BROKER_GRANT_KEY_OR_SIGNATURE_INVALID")
    canonical=registry.canonical({field:grant[field] for field in GRANT_FIELDS})
    try:
        Ed25519PublicKey.from_public_bytes(pub).verify(signature,canonical)
    except Exception as exc:
        raise CASRejected("SIGNED_CAS_BROKER_GRANT_SIGNATURE_NOT_VALID") from exc
    return {
        "contract":GRANT_CONTRACT,"state":"BROKER_CAS_RELEASE_GRANT_VERIFIED",
        "operation_id":OPERATION,"original_job_id":job,
        "company":plan["company"],"environment":plan["environment"],
        "expires_epoch":grant["expires_epoch"],
        "signed_release_grant_verified":True,
        "new_original_305_job_created":False
    }


def derivative_original_witness(job:str,plan:dict,authority:dict,signer,now:int)->dict:
    # This witness is derived from, never a replacement for, the already
    # verified Original 305/306/312 scope and content-pinned immutable plan.
    proof={
        "contract":"mad4b.company.original-executor-resource-cas.v1",
        "original_job_id":job,
        "company_code":plan["company"],
        "environment":plan["environment"],
        "site_uuid":plan["site_uuid"],
        "canonical_origin":plan["origin"],
        "native_operation":OPERATION,
        "source_plan_sha256":plan["source_plan_sha256"],
        "resource_type":plan["resource_type"],
        "resource_id":plan["resource_id"],
        "post_type":plan["post_type"],
        "meta_key":plan["meta_key"],
        "meta_id":plan["meta_id"],
        "expected_before_sha256":plan["expected_before_sha256"],
        "expected_manifest_sha256":plan["expected_manifest_sha256"],
        "expected_company_preservation_sha256":
            plan["expected_company_preservation_sha256"],
        "expected_meta_value_sha256":plan["expected_meta_value_sha256"],
        "new_meta_value_sha256":plan["new_meta_value_sha256"],
        "expected_after_sha256":plan["expected_after_sha256"],
        "issued_epoch":now,
        "expires_epoch":min(now+180,authority["expires_epoch"]-30),
        "nonce":os.urandom(16).hex(),
    }
    require(list(proof)==FIELDS and proof["expires_epoch"]>now+30,
            "ORIGINAL_CAS_DERIVATIVE_PROOF_EXPIRING")
    raw="\n".join(str(proof[f]) for f in FIELDS).encode()
    proof["signature"]=base64.b64encode(signer.sign(raw)).decode()
    return proof


PHP_CAS_APPLY=(
    '$proof=json_decode(base64_decode((string)getenv("MAD4B_ORIGINAL_CAS_PROOF_B64"),true),true);'
    '$value=base64_decode((string)getenv("MAD4B_ORIGINAL_CAS_VALUE_B64"),true);'
    '$result=is_array($proof)&&is_string($value)'
    '?MAD4B_Company_Executor_Time_CAS_V1::apply_signed($proof,$value)'
    ':["state"=>"EXECUTOR_CAS_HOLD","reason"=>"INVALID_SIGNED_ORIGINAL_WITNESS"];'
    'echo wp_json_encode($result,JSON_UNESCAPED_SLASHES);'
)


def target_call(container:str,actor:int,proof:dict,value:str,
                runner=subprocess.run)->dict:
    require(isinstance(container,str) and
            re.fullmatch(r"[a-f0-9]{64}",container) is not None
            and type(actor) is int and actor>0,
            "EXACT_ENROLLED_WORDPRESS_CONTAINER_AND_ACTOR_REQUIRED")
    token=base64.b64encode(json.dumps(
        proof,ensure_ascii=False,separators=(",",":")).encode()).decode()
    val=base64.b64encode(value.encode()).decode()
    command=[
       "/usr/bin/docker","exec","-u","33:33",
       "-e","MAD4B_ORIGINAL_CAS_PROOF_B64="+token,
       "-e","MAD4B_ORIGINAL_CAS_VALUE_B64="+val,
       container,"/usr/local/bin/wp","--path=/var/www/html",
       "--user="+str(actor),"eval",PHP_CAS_APPLY,
    ]
    # Call only after durable reservation. Timeout/uncertain commit
    # MUST NEVER be retried with a new job or stale before image.
    try:
        completed=runner(command,capture_output=True,timeout=45,check=False)
    except subprocess.TimeoutExpired as exc:
        raise CASRejected("SIGNED_TARGET_CAS_TIMEOUT_OUTCOME_UNKNOWN_NO_RETRY") from exc
    require(completed.returncode==0 and not completed.stderr
            and 0<len(completed.stdout)<=3500,
            "SIGNED_TARGET_CAS_RETURN_NOT_VERIFIED_NO_RETRY")
    try:
        result=json.loads(completed.stdout.strip().splitlines()[-1])
    except (UnicodeDecodeError,ValueError,IndexError) as exc:
        raise CASRejected("SIGNED_TARGET_CAS_JSON_NOT_VERIFIED_NO_RETRY") from exc
    require(isinstance(result,dict)
            and result.get("contract")==
                "mad4b.company.original-executor-resource-cas-result.v1"
            and result.get("state")==
                "ATOMIC_CAS_APPLIED_PENDING_INDEPENDENT_313"
            and result.get("original_job_id")==proof["original_job_id"]
            and result.get("resource_key")==
                proof["resource_type"]+":"+proof["resource_id"]
            and result.get("site_uuid")==proof["site_uuid"]
            and result.get("canonical_origin")==proof["canonical_origin"]
            and result.get("environment")==proof["environment"]
            and result.get("before_sha256")==proof["expected_before_sha256"]
            and result.get("after_sha256")==proof["expected_after_sha256"]
            and result.get("company_preservation_sha256")==
                proof["expected_company_preservation_sha256"]
            and result.get("before_cas_verified") is True
            and result.get("atomic_mutation_applied") is True
            and result.get("original_313_signed") is False
            and result.get("automatic_retry_authorized") is False,
            "SIGNED_TARGET_CAS_POSTCONDITION_NOT_VERIFIED")
    return result


def main(job:str,plan_sha:str):
    require(os.geteuid()==0,"ORIGINAL_ROOT_WORKER_ONLY")
    index,plan,authority,digest=pinned_plan(job,plan_sha)
    specific=verify_signed_specific_grant(job,plan,authority,digest)
    require(specific["signed_release_grant_verified"] is True,
            "SIGNED_CAS_PROVIDER_RELEASE_NOT_ADMITTED")
    host=module_from_root(WORDPRESS_HOST_PROOF,"original_cas_exact_host")
    central,target,container,_policy,_fingerprint,signer=host.info(
        plan["company"],plan["environment"])
    require(central.get("site_uuid")==plan["site_uuid"]
            and central.get("origin")==plan["origin"]
            and target.get("site_uuid")==plan["site_uuid"]
            and target.get("origin")==plan["origin"]
            and target.get("environment")==plan["environment"],
            "ORIGINAL_312_TARGET_SITE_ROTATED_OR_CHANGED")
    rawpub=base64.b64decode(BROKER_KEY.read_bytes().strip(),validate=True)
    from cryptography.hazmat.primitives.serialization import Encoding,PublicFormat
    pub=signer.public_key().public_bytes(Encoding.Raw,PublicFormat.Raw)
    require(len(rawpub)==32 and pub==rawpub,
            "ORIGINAL_DERIVATIVE_WITNESS_SIGNER_NOT_PINNED")
    issued=int(time.time())
    proof=derivative_original_witness(job,plan,authority,signer,issued)
    result=target_call(container,target["actor_user_id"],proof,
                       plan["new_meta_value"])
    # Signed independent 313 is NOT produced by this handler.
    receipt={
        "contract":"mad4b.original-resource-cas-host-receipt.v1",
        "state":"HOST_APPLIED_PENDING_INDEPENDENT_ORIGINAL_313",
        "job_id":job,"operation_id":OPERATION,
        "company":plan["company"],"environment":plan["environment"],
        "site_uuid":plan["site_uuid"],"origin":plan["origin"],
        "plan_sha256":plan_sha,"command_sha256":digest,
        "resource_key":result["resource_key"],
        "before_sha256":result["before_sha256"],
        "after_sha256":result["after_sha256"],
        "company_preservation_sha256":result["company_preservation_sha256"],
        "applied_epoch":int(time.time()),
        "target_cas_verified":True,
        "original_313_certified":False,
    }
    path=RECEIPTS/(job+".cas.json")
    fd=os.open(path,os.O_WRONLY|os.O_CREAT|os.O_EXCL|
               getattr(os,"O_NOFOLLOW",0),0o600)
    with os.fdopen(fd,"w") as stream:
        stream.write(json.dumps(receipt,sort_keys=True)+"\n")
        stream.flush();os.fsync(stream.fileno())
    print(json.dumps({
        "contract":"mad4b.original-resource-cas-host-handler.v1",
        "state":"HOST_APPLIED_PENDING_INDEPENDENT_ORIGINAL_313",
        "job_id":job,"plan_sha256":plan_sha,
        "original_305_job_issued_here":False,
        "original_312_verified":True,
        "original_313_certified":False
    }))


if __name__=="__main__":
    parser=argparse.ArgumentParser()
    parser.add_argument("--job",required=True)
    parser.add_argument("--plan-sha256",required=True)
    args=parser.parse_args()
    try:
        main(args.job,args.plan_sha256)
    except Exception as exc:
        print("ORIGINAL_CAS_HOLD:"+
              type(exc).__name__+":"+str(exc)[:140],file=sys.stderr)
        raise SystemExit(2)
