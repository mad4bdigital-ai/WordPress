"""Original 305/306/312 source-backed, one-use exact-resource CAS handler.

No independent queue, job or grant issuer. This handler is executed only by
the installed first-party dynamic 306 Worker after a claimed 305 Job has been
bound to this provider's immutable plan SHA. A separate independent Original
313 verifier is mandatory before any operation is declared certified.

NOT LIVE-ENROLLED: the original 313 finalizer must add dynamic provider
verification before a mutating release may register this handler.
"""
