'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const crypto = require('node:crypto');
const srcFile = process.env.MAD4B_STICKY_SCROLL_TEST_FILE || process.argv[2];
assert(srcFile);
const source = fs.readFileSync(srcFile, 'utf8');
const sha = crypto.createHash('sha256').update(source).digest('hex');
assert.equal(sha, 'f4c5da1f8939002f3df3b6ec4754dc57c41bea141281d038132bd59cbd3ca532');
const begin = source.indexOf('var scrollAnimationFrame = 0;');
const end = source.indexOf('var onWindowResize = function()', begin);
assert(begin !== -1 && end > begin, 'exact scroll lifecycle block exists');
const code = source.slice(begin, end);
assert(code.includes('window.requestAnimationFrame('));
const scheduled=[];
let nextFrameId=0;
const browser={requestAnimationFrame: fn => {scheduled.push(fn);return ++nextFrameId;}};
let checks=0;
const fixture=new Function('window','checkPosition',code+'return { onWindowScroll, pending: () => scrollAnimationFrame }');
const o=fixture(browser,()=>checks++);
for(let i=0;i<100;i++)o.onWindowScroll();
assert.equal(scheduled.length,1,'one scroll check scheduled for burst');
assert.equal(checks,0,'scroll handler does not synchronously force layout');
assert.equal(o.pending(),1);
scheduled.shift()();
assert.equal(checks,1,'one geometry read after animation frame');
assert.equal(o.pending(),0,'coalescing lock released');
o.onWindowScroll();
assert.equal(scheduled.length,1,'next frame can schedule again');
assert.equal(o.pending(),2);
const resize=source.slice(source.indexOf('var onWindowResize = function()', end),source.indexOf('this.destroy = function()', end));
const destroy=source.slice(source.indexOf('this.destroy = function()', end),source.indexOf('init();',end));
for(const [which,s] of [['resize',resize],['destroy',destroy]]){
 assert(s.includes('window.cancelAnimationFrame( scrollAnimationFrame )'),which+' cancels pending check');
 assert(s.includes('scrollAnimationFrame = 0;'),which+' clears pending token');
}
assert(source.includes("$element.clone( false, false ).empty()"),'existing Form6 hidden/visible shell stays');
assert(source.includes('containsFluentBooking'),'existing Form6 safety guard stays');
console.log('PASS one scroll calculation per frame');
console.log('PASS a new frame schedules after callback');
console.log('PASS resize and destroy cancel pending frame');
console.log('PASS Form6-safe Sticky spacer intact');
console.log('ALL_STICKY_SCROLL_COALESCE_TESTS_PASS');
